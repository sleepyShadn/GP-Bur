  /// Returns the new analysis document id on success, or null on failure.
  Future<String?> saveAnalysisToFirestore({
    required String userId,
    required String text,
    required String classification,
    required String goal,
    required DateTime startDate,
    required int duration,
    required List<Map<String, dynamic>> activities,
    bool professionalEscalation = false,
  }) async {
    if (userId.isEmpty) return null;

    try {
      DateTime expiryDate = startDate.add(Duration(days: duration));
      String analysisId = DateTime.now().millisecondsSinceEpoch.toString();

      Map<String, dynamic> analysisData = {
        'timestamp': FieldValue.serverTimestamp(),
        'text': text,
        'classification': classification,
        'goal': goal,
        'goalStartDate': startDate,
        'goalDurationDays': duration,
        'goalExpiryDate': expiryDate,
        'isGoalCompleted': false,
        'professionalEscalation': professionalEscalation,
        'activities': activities.map((activity) => {
          'title': activity['title'],
          'points': activity['points'],
          'completed': activity['completed'],
          'activityId': activity['activityId'],
          'lastCompletedDate': activity['lastCompletedDate'],
          'dailyHistory': activity['dailyHistory'],
        }).toList(),
        'collectedInfo': _collectedInfo,
        'questionsAsked': _questions,
      };

      await _firestore
          .collection('users')
          .doc(userId)
          .collection('analyses')
          .doc(analysisId)
          .set(analysisData);

      // Reset collection after saving
      resetCollection();

      return analysisId;
    } catch (e) {
      print('Error saving analysis: $e');
      return null;
    }
  }

  /// Fires when the user completes **exactly three check-ins in a row** whose
  /// stored [classification] matches (case-insensitive). Uses Firestore only;
  /// the label is never shown in the main UI—only this notification/inbox row.
  ///
  /// A 4th consecutive same classification does not notify again until the
  /// streak breaks and later reaches three again.
  Future<bool> checkForRecurringDiagnosis(
    String userId,
    String newDiagnosis,
    String newlySavedAnalysisId,
  ) async {
    if (userId.isEmpty ||
        newDiagnosis.trim().isEmpty ||
        newlySavedAnalysisId.trim().isEmpty) {
      return false;
    }

    final String norm = newDiagnosis.trim().toLowerCase();
    if (norm == kProfessionalSupportReferralClassification) {
      return false;
    }

    QuerySnapshot<Map<String, dynamic>>? snap;

    for (int attempt = 0; attempt < 3; attempt++) {
      if (attempt > 0) {
        await Future<void>.delayed(const Duration(milliseconds: 400));
      }
      snap = await _firestore
          .collection('users')
          .doc(userId)
          .collection('analyses')
          .orderBy('timestamp', descending: true)
          .limit(16)
          .get();

      if (snap.docs.isNotEmpty && snap.docs.first.id == newlySavedAnalysisId) {
        break;
      }
    }

    if (snap == null ||
        snap.docs.isEmpty ||
        snap.docs.first.id != newlySavedAnalysisId) {
      return false;
    }

    int consecutive = 0;
    for (final QueryDocumentSnapshot<Map<String, dynamic>> doc in snap.docs) {
      final String c =
          (doc.data()['classification'] ?? '').toString().trim().toLowerCase();
      if (c == norm && c.isNotEmpty) {
        consecutive++;
      } else {
        break;
      }
    }

    if (consecutive != 3) {
      return false;
    }

    const String title = 'Your check-ins follow a similar theme';
    const String body =
        'Bur noticed your last three daily check-ins landed in a similar emotional space. '
        'That can feel heavy—when you are ready, consider talking with someone you trust or a licensed professional. '
        'Small steps in the app still count.';

    await _notificationService.showLocalNotificationOnly(
      title: title,
      body: body,
      payload: 'recurring_diagnosis',
      inboxUserId: userId,
      persistToInbox: false,
    );

    await LocalNotificationInboxStore.instance.append(
      userId: userId,
      title: title,
      body: body,
      type: 'recurring_diagnosis',
    );

    return true;
  }

  Future<bool> toggleActivity(String userId, String analysisId, int index, Map<String, dynamic> activity) async {
    try {
      final DocumentReference userRef =
          _firestore.collection('users').doc(userId);
      final DocumentReference analysisRef = userRef
          .collection('analyses')
          .doc(analysisId);

      DocumentSnapshot analysisDoc = await analysisRef.get();
      if (!analysisDoc.exists) return false;

      final Map<String, dynamic> data = analysisDoc.data() as Map<String, dynamic>;
      final List<dynamic> activities = List<dynamic>.from(data['activities'] ?? []);
      if (index >= activities.length) return false;

      final bool isGoalCompleted = data['isGoalCompleted'] ?? false;
      if (isGoalCompleted) {
        return false;
      }

      final DateTime now = DateTime.now();
      final String todayKey = '${now.year}-${now.month}-${now.day}';
      final Map<String, dynamic> target =
          Map<String, dynamic>.from(activities[index] as Map);
      final Map<String, dynamic> history = Map<String, dynamic>.from(
        target['dailyHistory'] as Map? ?? <String, dynamic>{},
      );
      final bool isCompletedToday = history[todayKey] == true;
      final bool newValue = !isCompletedToday;
      final int points = (target['points'] as num?)?.toInt() ?? 5;

      target['completed'] = newValue;
      target['lastCompletedDate'] = newValue ? Timestamp.fromDate(now) : null;
      history[todayKey] = newValue;
      target['dailyHistory'] = history;
      activities[index] = target;

      await analysisRef.update(<String, dynamic>{'activities': activities});

      if (newValue) {
        await userRef.update(<String, dynamic>{
          'points': FieldValue.increment(points),
        });
      } else {
        final DocumentSnapshot userDoc = await userRef.get();
        final int currentPoints =
            ((userDoc.data() as Map<String, dynamic>?)?['points'] as num?)
                    ?.toInt() ??
                0;
        final int updatedPoints = (currentPoints - points).clamp(0, 1 << 31);
        await userRef.update(<String, dynamic>{'points': updatedPoints});
      }
      return true;
    } catch (e) {
      print('Error updating activity: $e');
    }
    return false;
  }
